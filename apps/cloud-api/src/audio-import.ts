import type { FastifyInstance, FastifyRequest } from "fastify";
import { z } from "zod";
import {
  AudioFileImportSchema,
  AudioPreviewLimitMs,
  AudioSpeechTranscriptSchema,
  AudioUrlImportSchema,
  CreateSourceRequestSchema,
  MaxAudioBytes,
  type AudioAssetManifest,
  type AuthenticatedActor,
} from "@research-video/contracts";
import {
  CaptureDenied,
  inspectPublicUrl,
  NodePinnedTransport,
  PublicEgressGuard,
  SystemDnsResolver,
} from "@research-video/providers/public-egress";
import {
  InvalidAudio,
  preparePublicAudio,
} from "@research-video/providers/library-audio-media";
import type { CloudApiDependencies } from "./app.ts";

const ProjectParams = z.object({ projectId: z.uuid() });
const SourceParams = ProjectParams.extend({ sourceId: z.uuid() });
const base = "/api/projects/:projectId/audio";

export type PublicAudioReader = (url: string) => Promise<Buffer>;
export type PublicAudioPreparation = typeof preparePublicAudio;

class AudioImportError extends Error {
  readonly code = "audio_import_failed";

  constructor(
    readonly statusCode: number,
    message: string,
  ) {
    super(message);
  }
}

function createPublicAudioReader(): PublicAudioReader {
  const guard = new PublicEgressGuard(
    new SystemDnsResolver(),
    new NodePinnedTransport(),
    { maxRedirects: 5, maxResponseBytes: MaxAudioBytes },
  );
  let active = 0;
  return async (url) => {
    if (active >= 2)
      throw new AudioImportError(
        429,
        "Other audio is downloading. Try again shortly.",
      );
    active++;
    const abort = new AbortController();
    let timer: ReturnType<typeof setTimeout> | undefined;
    const deadline = new Promise<never>((_, reject) => {
      timer = setTimeout(() => {
        abort.abort();
        reject(new AudioImportError(504, "The audio download timed out."));
      }, 20_000);
    });
    // Even a pending system DNS call keeps its slot after the request times out.
    const download = guard
      .fetch(url, "GET", abort.signal)
      .finally(() => active--);
    try {
      const result = await Promise.race([download, deadline]);
      if (result.status !== 200)
        throw new AudioImportError(
          422,
          "The link did not return a public audio file.",
        );
      return result.body;
    } finally {
      clearTimeout(timer);
    }
  };
}

function checkedPreview(bytes: Buffer, durationMs: number) {
  // Admit only the fixed, metadata-free PCM layout generated by Research.
  const dataSize = bytes.length - 44;
  const previewMs = Math.max(1, Math.round(dataSize / 16));
  if (
    dataSize < 2 ||
    dataSize % 2 !== 0 ||
    dataSize > AudioPreviewLimitMs * 16 ||
    bytes.toString("ascii", 0, 4) !== "RIFF" ||
    bytes.readUInt32LE(4) !== bytes.length - 8 ||
    bytes.toString("ascii", 8, 16) !== "WAVEfmt " ||
    bytes.readUInt32LE(16) !== 16 ||
    bytes.readUInt16LE(20) !== 1 ||
    bytes.readUInt16LE(22) !== 1 ||
    bytes.readUInt32LE(24) !== 8000 ||
    bytes.readUInt32LE(28) !== 16000 ||
    bytes.readUInt16LE(32) !== 2 ||
    bytes.readUInt16LE(34) !== 16 ||
    bytes.toString("ascii", 36, 40) !== "data" ||
    bytes.readUInt32LE(40) !== dataSize ||
    Math.abs(previewMs - Math.min(durationMs, AudioPreviewLimitMs)) > 1
  )
    throw new AudioImportError(
      400,
      "The audio preview is invalid. Select the file again.",
    );
  return Math.min(previewMs, durationMs);
}

export function registerAudioRoutes(
  app: FastifyInstance,
  dependencies: CloudApiDependencies,
) {
  const { catalog, authenticate } = dependencies;
  const readPublicAudio =
    dependencies.publicAudioReader ?? createPublicAudioReader();
  const prepareAudio =
    dependencies.publicAudioPreparation ?? preparePublicAudio;
  const writes = new WeakMap<FastifyRequest, AuthenticatedActor>();
  let inFlight = 0;
  const finish = (request: FastifyRequest) => {
    if (writes.delete(request)) inFlight--;
  };
  app.addHook("onRequest", async (request) => {
    if (request.method !== "POST") return;
    const { projectId } = ProjectParams.parse(request.params);
    const actor = await authenticate(request);
    await catalog.authorizeSourceWrite(actor, projectId);
    if (inFlight >= 2)
      throw new AudioImportError(
        429,
        "Other audio is being imported. Try again shortly.",
      );
    writes.set(request, actor);
    inFlight++;
  });
  app.addHook("onResponse", async (request) => finish(request));
  app.addHook("onRequestAbort", async (request) => finish(request));

  const publish = (
    request: FastifyRequest,
    {
      title,
      role,
      idempotencyKey,
      url,
    }: {
      title: string;
      role?: z.infer<typeof AudioFileImportSchema>["role"];
      idempotencyKey: string;
      url?: string;
    },
    analysis: Omit<AudioAssetManifest, "playbackSha256">,
    bytes: Buffer,
  ) => {
    const { projectId } = ProjectParams.parse(request.params);
    const actor = writes.get(request);
    if (!actor)
      throw new AudioImportError(400, "The audio import was interrupted.");
    return catalog.library.publishAudio(
      actor,
      projectId,
      CreateSourceRequestSchema.parse({
        kind: "audio",
        bibliography: {
          title: { value: title, state: "confirmed" },
          ...(url && { url: { value: url, state: "confirmed" } }),
        },
        details: { role, durationMs: analysis.durationMs },
        idempotencyKey,
      }),
      analysis,
      bytes,
    );
  };

  app.post(
    base + "/from-file",
    { bodyLimit: 350 * 1024 },
    async (request, reply) => {
      const { peaks, durationMs, originalSha256, previewBase64, ...metadata } =
        AudioFileImportSchema.parse(request.body);
      const preview = Buffer.from(previewBase64, "base64");
      const source = await publish(
        request,
        metadata,
        {
          durationMs,
          peaks,
          playbackDurationMs: checkedPreview(preview, durationMs),
          origin: { kind: "file", originalSha256 },
          mimeType: "audio/wav",
        },
        preview,
      );
      return reply.code(201).send(source);
    },
  );

  app.post(base + "/from-url", { bodyLimit: 8192 }, async (request, reply) => {
    const { url, ...metadata } = AudioUrlImportSchema.parse(request.body);
    try {
      const { canonicalUrl } = inspectPublicUrl(url);
      const bytes = await readPublicAudio(canonicalUrl);
      if (bytes.length > MaxAudioBytes)
        throw new AudioImportError(
          413,
          "This audio exceeds the import size limit.",
        );
      const analysis = await prepareAudio(bytes);
      const source = await publish(
        request,
        { ...metadata, url: canonicalUrl },
        {
          ...analysis,
          playbackDurationMs: analysis.durationMs,
          origin: { kind: "url" },
        },
        bytes,
      );
      return reply.code(201).send(source);
    } catch (error) {
      if (error instanceof CaptureDenied)
        throw new AudioImportError(
          error.code === "response_too_large" ? 413 : 400,
          error.safeMessage,
        );
      if (error instanceof InvalidAudio)
        throw new AudioImportError(422, error.message);
      throw error;
    }
  });

  app.get(base + "/:sourceId", async (request, reply) => {
    const { projectId, sourceId } = SourceParams.parse(request.params);
    reply.header("Cache-Control", "private, no-store");
    return catalog.library.getAudioManifest(
      await authenticate(request),
      projectId,
      sourceId,
    );
  });

  const transcriptPath = base + "/:sourceId/transcript";
  app.get(transcriptPath, async (request, reply) => {
    const { projectId, sourceId } = SourceParams.parse(request.params);
    reply.header("Cache-Control", "private, no-store");
    return {
      transcript: await catalog.library.getAudioTranscript(
        await authenticate(request),
        projectId,
        sourceId,
      ),
    };
  });

  app.post(
    transcriptPath,
    { bodyLimit: 768 * 1024 },
    async (request, reply) => {
      const { projectId, sourceId } = SourceParams.parse(request.params);
      const actor = writes.get(request);
      if (!actor)
        throw new AudioImportError(400, "The audio request was interrupted.");
      reply.header("Cache-Control", "private, no-store");
      const action = z
        .discriminatedUnion("mode", [
          z.strictObject({
            mode: z.enum(["file", "kept_audio"]),
            transcript: AudioSpeechTranscriptSchema,
          }),
          z.strictObject({ mode: z.literal("url") }),
        ])
        .parse(request.body);
      if (action.mode !== "url") {
        return catalog.library.publishAudioTranscript(
          actor,
          projectId,
          sourceId,
          action.transcript,
          action.mode === "file" ? "file" : "url",
        );
      }
      const source = await catalog.library.getSource(
        actor,
        projectId,
        sourceId,
      );
      const manifest = await catalog.library.getAudioManifest(
        actor,
        projectId,
        sourceId,
      );
      if (manifest.origin.kind !== "url")
        throw new AudioImportError(
          400,
          "Relink the original in the workstation app to transcribe this file.",
        );
      if (
        source.kind !== "audio" ||
        !("role" in source.details) ||
        source.details.role !== "speech"
      )
        throw new AudioImportError(
          409,
          "Set the source role to Speech before transcribing.",
        );
      const existing = await catalog.library.getAudioTranscript(
        actor,
        projectId,
        sourceId,
      );
      if (existing) return existing;
      if (!dependencies.transcribePublicAudio)
        throw new AudioImportError(
          503,
          "Local Whisper is unavailable on the Research host.",
        );
      const object = await catalog.library.getAudioPlayback(
        actor,
        projectId,
        sourceId,
      );
      const abort = new AbortController();
      const cancel = () => abort.abort();
      reply.raw.once("close", cancel);
      try {
        const transcript = await dependencies.transcribePublicAudio(
          sourceId,
          Buffer.from(object.bytes),
          manifest.durationMs,
          abort.signal,
        );
        abort.signal.throwIfAborted();
        return await catalog.library.publishAudioTranscript(
          actor,
          projectId,
          sourceId,
          transcript,
          "url",
        );
      } finally {
        reply.raw.off("close", cancel);
      }
    },
  );

  app.get(base + "/:sourceId/playback", async (request, reply) => {
    const { projectId, sourceId } = SourceParams.parse(request.params);
    const object = await catalog.library.getAudioPlayback(
      await authenticate(request),
      projectId,
      sourceId,
    );
    return reply
      .header("Cache-Control", "private, no-store")
      .header("X-Content-Type-Options", "nosniff")
      .type(object.contentType)
      .send(Buffer.from(object.bytes));
  });
}
