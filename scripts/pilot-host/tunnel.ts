/**
 * cloudflared configuration for the friends-only pilot (#53).
 *
 * The tunnel is outbound-only: no router port is opened. It forwards exactly
 * one public hostname to the loopback BFF port, refuses operator paths at the
 * edge connector, asks cloudflared to validate the Access token as well, and
 * ends with a catch-all 404 so no other hostname or service is reachable.
 */
export type TunnelSettings = {
  tunnelId: string;
  credentialsFile: string;
  hostname: string;
  originPort: number;
  operatorPort: number;
  metricsPort: number;
  accessTeamName: string;
  accessAud: string;
};

const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/u;
const label = /^(?!-)[a-z0-9-]{1,63}(?<!-)$/u;

export function validateTunnelSettings(settings: TunnelSettings): void {
  const problems: string[] = [];
  if (!uuid.test(settings.tunnelId))
    problems.push("tunnel id must be the tunnel's UUID");
  if (
    !settings.credentialsFile.startsWith("/") ||
    /[\n\r"]/u.test(settings.credentialsFile)
  )
    problems.push("credentials file must be an absolute path");
  const parts = settings.hostname.split(".");
  if (
    parts.length < 3 ||
    !parts.every((part) => label.test(part)) ||
    settings.hostname.length > 253
  )
    problems.push(
      "hostname must be one exact lowercase subdomain such as research.example.com (no wildcards)",
    );
  for (const [name, port] of [
    ["origin port", settings.originPort],
    ["metrics port", settings.metricsPort],
    ["operator port", settings.operatorPort],
  ] as const)
    if (!Number.isInteger(port) || port < 1024 || port > 65_535)
      problems.push(`${name} must be an unprivileged port`);
  if (
    new Set([settings.originPort, settings.metricsPort, settings.operatorPort])
      .size !== 3
  )
    problems.push("origin, operator and metrics ports must all differ");
  if (!label.test(settings.accessTeamName))
    problems.push(
      "Access team name must be the <team> in <team>.cloudflareaccess.com",
    );
  if (!/^[0-9a-f]{64}$/u.test(settings.accessAud))
    problems.push("Access audience tag must be 64 hex characters");
  if (problems.length > 0)
    throw new Error(`Invalid tunnel settings: ${problems.join("; ")}`);
}

/** Renders cloudflared's config.yml. All values are validated first. */
export function renderTunnelConfig(settings: TunnelSettings): string {
  validateTunnelSettings(settings);
  const host = settings.hostname;
  return `# Generated by \`npm run pilot -- tunnel-config\` (#53). Do not hand-edit.
# Outbound-only Cloudflare Tunnel: no router ports are opened.
tunnel: ${settings.tunnelId}
credentials-file: "${settings.credentialsFile}"
no-autoupdate: true
metrics: 127.0.0.1:${settings.metricsPort}
ingress:
  # Operator and maintenance paths never leave the laptop.
  - hostname: ${host}
    path: ^/(cloud-api/)?__(maintenance|operator)(/|$)
    service: http_status:404
  - hostname: ${host}
    service: http://127.0.0.1:${settings.originPort}
    originRequest:
      connectTimeout: 10s
      # cloudflared also rejects requests without a valid Access token.
      access:
        required: true
        teamName: ${settings.accessTeamName}
        audTag:
          - ${settings.accessAud}
  # Anything else (other hostnames, direct IP access) gets a 404.
  - service: http_status:404
`;
}
