function sanitizeFailure(error: unknown): string {
  const message = error instanceof Error ? error.message : "";
  if (message.includes("invalid_operation_reference"))
    return "invalid_operation_reference";
  if (message.includes("integrity")) return "integrity_check_failed";
  if (message.includes("not_found")) return "source_or_candidate_not_found";
  if (message.includes("unavailable")) return "source_unavailable";
  return "local_model_operation_failed";
}

function sanitizeFailureCode(code: string): string {
  const normalized = code
    .trim()
    .replace(/[^a-z0-9._-]/gi, "_")
    .slice(0, 160);
  return normalized || "local_model_operation_failed";
}

function assertOperationReference(input: EnqueueLocalModelOperation): void {
  const source = input.sourceId !== undefined;
  const candidate = input.candidateId !== undefined;
  const release = input.catalogReleaseId !== undefined;
  const valid =
    (input.kind === "refresh_source" && source && !candidate && !release) ||
    (["evaluate_candidate", "mirror_artifact"].includes(input.kind) &&
      !source &&
      candidate &&
      !release) ||
    (input.kind === "publish_catalog_release" &&
      !source &&
      !candidate &&
      release);
  if (!valid) throw new Error("invalid_operation_reference");
}

function sameOperationIntent(
  operation: DurableLocalModelOperation,
  input: EnqueueLocalModelOperation,
): boolean {
  return (
    operation.kind === input.kind &&
    operation.sourceId === input.sourceId &&
    operation.candidateId === input.candidateId &&
    operation.catalogReleaseId === input.catalogReleaseId
  );
}

function sha256(bytes: Uint8Array): string {
  return sha256Bytes(bytes);
}

function sha256Bytes(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

function stableJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.entries(value as Record<string, unknown>)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([key, item]) => `${JSON.stringify(key)}:${stableJson(item)}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}
