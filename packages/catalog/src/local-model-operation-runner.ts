export type ImmutableArtifact = {
  id: string;
  sha256: string;
  byteSize: number;
};

export interface ImmutableArtifactStore {
  putImmutable(
    kind: "raw_feed" | "raw_candidate" | "artifact" | "evaluation",
    bytes: Uint8Array,
  ): Promise<ImmutableArtifact>;
  read(id: string): Promise<Uint8Array>;
}

/** Small object-store boundary used by the server composition layer. */
export interface ImmutableByteObjectStore {
  putIfAbsent(key: string, bytes: Uint8Array): Promise<void>;
  get(key: string): Promise<Uint8Array | undefined>;
}

export class TranscriptImmutableByteObjectStore implements ImmutableByteObjectStore {
  constructor(private readonly objects: TranscriptObjectStore) {}

  async putIfAbsent(key: string, bytes: Uint8Array): Promise<void> {
    const expected = sha256Bytes(bytes);
    const existing = await this.objects.get(key);
    if (existing) {
      if (existing.sha256 !== expected)
        throw new Error("immutable_key_collision");
      return;
    }
    const stored = await this.objects.put({
      key,
      bytes,
      contentType: "application/octet-stream",
      sha256: expected,
    });
    if (stored.sha256 !== expected)
      throw new Error("artifact_integrity_mismatch");
  }

  async get(key: string): Promise<Uint8Array | undefined> {
    const stored = await this.objects.get(key);
    if (!stored) return undefined;
    if (sha256Bytes(stored.bytes) !== stored.sha256)
      throw new Error("artifact_integrity_mismatch");
    return stored.bytes;
  }
}

export class ContentAddressedImmutableArtifactStore implements ImmutableArtifactStore {
  constructor(private readonly objects: ImmutableByteObjectStore) {}
  async putImmutable(
    kind: "raw_feed" | "raw_candidate" | "artifact" | "evaluation",
    bytes: Uint8Array,
  ): Promise<ImmutableArtifact> {
    const sha256 = sha256Bytes(bytes);
    const id = `language-model/${kind}/${sha256}`;
    await this.objects.putIfAbsent(id, bytes);
    return { id, sha256, byteSize: bytes.byteLength };
  }
  async read(id: string): Promise<Uint8Array> {
    const bytes = await this.objects.get(id);
    if (!bytes) throw new Error("immutable_artifact_missing");
    return bytes;
  }
}

export interface ArgosSourceAdapter {
  fetchFeed(sourceUrl: string): Promise<string>;
  fetchArtifact(artifactUrl: string): Promise<Uint8Array>;
}

export class HttpArgosSourceAdapter implements ArgosSourceAdapter {
  constructor(
    private readonly fetcher: typeof fetch = fetch,
    private readonly maxFeedBytes = 20_000_000,
    private readonly maxArtifactBytes = 1_000_000_000,
  ) {}

  async fetchFeed(sourceUrl: string): Promise<string> {
    const bytes = await this.#fetchBounded(sourceUrl, this.maxFeedBytes);
    return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  }

  async fetchArtifact(artifactUrl: string): Promise<Uint8Array> {
    return this.#fetchBounded(artifactUrl, this.maxArtifactBytes);
  }

  async #fetchBounded(url: string, maxBytes: number): Promise<Uint8Array> {
    const parsed = new URL(url);
    if (parsed.protocol !== "https:") throw new Error("unsafe_source_url");
    const response = await this.fetcher(parsed, {
      redirect: "follow",
      signal: AbortSignal.timeout(60_000),
      headers: { accept: "application/octet-stream, application/json" },
    });
    if (!response.ok) throw new Error("source_fetch_failed");
    if (new URL(response.url || parsed).protocol !== "https:")
      throw new Error("unsafe_source_url");
    const declared = Number(response.headers.get("content-length"));
    if (Number.isFinite(declared) && declared > maxBytes)
      throw new Error("source_byte_limit_exceeded");
    const bytes = new Uint8Array(await response.arrayBuffer());
    if (bytes.byteLength === 0 || bytes.byteLength > maxBytes)
      throw new Error("source_byte_limit_exceeded");
    return bytes;
  }
}

